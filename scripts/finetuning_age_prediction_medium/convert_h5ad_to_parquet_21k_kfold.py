#!/usr/bin/env python3
"""
Convert 21k AltumAge h5ad dataset to MethylGPT parquet format, for 5-fold CV.

Adapted from convert_h5ad_to_parquet_21k.py. Instead of using adata.obs["split"],
row selection for each fold's train/valid (and the shared, fixed test set) is
driven by external GSM-ID lists (.npy files) generated by the sibling MethylLlama
V7b repo's create_kfold_splits.py (StratifiedKFold, random_state=42, stratified by
age_bin(10yr) x tissue_type). This reproduces the *exact* fold membership used
there, rather than an independent split, so the two models are comparable fold
for fold.

GSM ID is the join key: each split's GSM IDs are matched against adata.obs_names
(the h5ad's own GSM-ID index) via a boolean mask, then rows/ages are pulled out
of the same CpG-aligned methylation matrix the original script builds. Row order
within each output parquet follows the h5ad's own order (not the .npy's), which
is fine since neither training nor evaluation depends on row order.

Usage (on cluster):
    # One-time: builds train_fold{0..4}.parquet, valid_fold{0..4}.parquet, and
    # the single shared test.parquet, all in one h5ad load.
    python convert_h5ad_to_parquet_21k_kfold.py

    # Only specific folds, skip rebuilding the shared test set:
    python convert_h5ad_to_parquet_21k_kfold.py --folds 0 2 --skip_test
"""

import argparse
from pathlib import Path

import anndata
import numpy as np
import pandas as pd


def load_gsm_ids(npy_path: Path) -> np.ndarray:
    ids = np.load(npy_path, allow_pickle=True)
    id_arr = np.asarray([str(x) for x in ids], dtype=str)
    if len(id_arr) != len(set(id_arr)):
        raise ValueError(f"{npy_path}: duplicate GSM IDs within the file itself")
    return id_arr


def select_and_build_df(
    methyl_aligned: pd.DataFrame,
    ages: np.ndarray,
    obs_names_arr: np.ndarray,
    ids: np.ndarray,
    label: str,
) -> pd.DataFrame:
    mask = np.isin(obs_names_arr, ids)
    found = obs_names_arr[mask]
    missing = set(ids) - set(found)
    if missing:
        example = sorted(missing)[:5]
        raise ValueError(
            f"{label}: {len(missing)} GSM IDs from split file not found in h5ad "
            f"obs_names (e.g. {example})"
        )
    if mask.sum() != len(ids):
        raise ValueError(
            f"{label}: expected {len(ids)} rows, matched {mask.sum()} "
            "(unexpected duplicate obs_names in h5ad?)"
        )

    rows = methyl_aligned.loc[mask].values
    split_ages = ages[mask]

    return pd.DataFrame({
        "data": [row.tolist() for row in rows],
        "age": split_ages.tolist(),
    })


def convert(
    h5ad_path: str,
    probe_id_csv: str,
    kfold_splits_dir: str,
    output_dir: str,
    folds: list,
    build_test: bool,
) -> None:
    kfold_splits_dir = Path(kfold_splits_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # ── Load h5ad ───────────────────────────────────────────────────────────
    print(f"Loading {h5ad_path} ...")
    adata = anndata.read_h5ad(h5ad_path)
    print(f"  Shape: {adata.shape}")
    if not adata.obs_names.is_unique:
        raise ValueError("adata.obs_names (GSM IDs) are not unique — cannot join safely")
    obs_names_arr = np.asarray(adata.obs_names, dtype=str)

    # ── Load 49k CpG reference ───────────────────────────────────────────────
    cpg_ref = pd.read_csv(probe_id_csv)["illumina_probe_id"].tolist()
    print(f"  Reference CpGs: {len(cpg_ref):,}")

    # ── Build methylation DataFrame (samples × 21k CpGs) ────────────────────
    X = adata.X
    if hasattr(X, "toarray"):
        X = X.toarray()
    X = X.astype(np.float32)

    methyl_df = pd.DataFrame(X, index=adata.obs_names, columns=adata.var_names)

    # Align to 49k reference — missing CpGs become NaN
    methyl_aligned = methyl_df.reindex(columns=cpg_ref)
    n_present = methyl_df.columns.isin(cpg_ref).sum()
    print(f"  CpGs present in reference: {n_present:,} / {len(adata.var_names):,}")

    ages = adata.obs["age"].values

    # ── Shared, fixed test set (built once, identical across all folds) ────
    if build_test:
        test_ids = load_gsm_ids(kfold_splits_dir / "test_ids.npy")
        df_test = select_and_build_df(methyl_aligned, ages, obs_names_arr, test_ids, "test")
        out_path = output_dir / "test.parquet"
        df_test.to_parquet(out_path, index=False)
        print(f"  Saved test: {len(df_test):,} samples → {out_path}")

    # ── Per-fold train/valid ─────────────────────────────────────────────────
    for fold in folds:
        train_ids = load_gsm_ids(kfold_splits_dir / f"fold_{fold}_train.npy")
        val_ids = load_gsm_ids(kfold_splits_dir / f"fold_{fold}_val.npy")

        df_train = select_and_build_df(
            methyl_aligned, ages, obs_names_arr, train_ids, f"fold{fold}_train"
        )
        df_val = select_and_build_df(
            methyl_aligned, ages, obs_names_arr, val_ids, f"fold{fold}_val"
        )

        train_out = output_dir / f"train_fold{fold}.parquet"
        val_out = output_dir / f"valid_fold{fold}.parquet"
        df_train.to_parquet(train_out, index=False)
        df_val.to_parquet(val_out, index=False)
        print(f"  Saved fold {fold} train: {len(df_train):,} samples → {train_out}")
        print(f"  Saved fold {fold} valid: {len(df_val):,} samples → {val_out}")

    print("Done.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--h5ad",
        default="/sci/labs/benjamin.yakir/netanel.azran/data/"
                "data_methyl_21k_h5ad/altumage_21k_3way.h5ad",
    )
    parser.add_argument(
        "--probe_id_csv",
        default="/sci/labs/benjamin.yakir/netanel.azran/MethylGPT/data/"
                "cpg_ids/probe_ids_type3.csv",
    )
    parser.add_argument(
        "--kfold_splits_dir",
        default="/sci/labs/benjamin.yakir/netanel.azran/MethylGPT/data/"
                "21k_altumage/kfold_splits",
        help="Directory holding fold_{0..4}_train.npy, fold_{0..4}_val.npy, and "
             "test_ids.npy, synced from the methyl repo's outputs/kfold_splits/ "
             "on the cluster. Do NOT regenerate these — copy them as-is.",
    )
    parser.add_argument(
        "--output_dir",
        default="/sci/labs/benjamin.yakir/netanel.azran/MethylGPT/data/"
                "21k_altumage/finetuning_data_kfold",
    )
    parser.add_argument(
        "--folds",
        type=int,
        nargs="+",
        choices=[0, 1, 2, 3, 4],
        default=[0, 1, 2, 3, 4],
        help="Which fold indices to build train/valid parquet for.",
    )
    parser.add_argument(
        "--skip_test",
        action="store_true",
        help="Skip (re)building the shared test.parquet.",
    )
    args = parser.parse_args()
    convert(
        args.h5ad,
        args.probe_id_csv,
        args.kfold_splits_dir,
        args.output_dir,
        args.folds,
        build_test=not args.skip_test,
    )
